import { expect, test } from '@playwright/test';

test('Knowledge collections demo matches the record workspace and keeps add/search local', async ({ page }) => {
  const apiRequests: string[] = [];
  page.on('request', request => { if (new URL(request.url()).pathname.startsWith('/api/')) apiRequests.push(request.url()); });
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.addInitScript(() => localStorage.setItem('oa-second-data-mode', 'demo'));
  await page.goto('/?view=knowledge');
  await page.getByRole('tab', { name: 'Collections' }).click();

  await expect(page.getByRole('heading', { name: 'Collections · demo records' })).toBeVisible();
  await expect(page.getByRole('textbox', { name: 'Search collections' })).toBeVisible();
  await expect(page.getByText('Product documentation', { exact: true })).toBeVisible();
  await expect(page.getByText('Engineering notes', { exact: true })).toBeVisible();
  await expect(page.getByText('Research references', { exact: true })).toBeVisible();
  await expect(page.getByText('collections', { exact: true })).toBeVisible();

  await page.getByRole('textbox', { name: 'Search collections' }).fill('Engineering');
  await expect(page.getByText('Engineering notes', { exact: true })).toBeVisible();
  await expect(page.getByText('Product documentation', { exact: true })).toHaveCount(0);
  await page.getByRole('textbox', { name: 'Search collections' }).fill('');
  await page.getByRole('button', { name: 'Open Product documentation' }).click();
  await expect(page.getByRole('dialog', { name: 'Product documentation' })).toBeVisible();
  await expect(page.getByText('Vector collection details · local demo data')).toBeVisible();
  await page.getByRole('button', { name: 'Close collection details' }).click();

  await page.getByRole('button', { name: 'Add', exact: true }).click();
  const addDialog = page.getByRole('dialog', { name: 'Add collection' });
  await expect(addDialog).toBeVisible();
  const collectionName = page.getByRole('textbox', { name: 'Collection name' });
  await collectionName.fill('');
  await expect(collectionName).toHaveJSProperty('validity.valid', false);
  await expect(addDialog.getByRole('button', { name: 'Add collection' })).toBeDisabled();
  await collectionName.fill('Desktop QA collection');
  await page.getByRole('button', { name: 'Add collection' }).click();
  await expect(page.getByRole('tab', { name: 'Collections' })).toHaveAttribute('aria-selected', 'true');
  await expect(page.getByText('Desktop QA collection', { exact: true })).toBeVisible();
  await page.reload();
  await page.getByRole('tab', { name: 'Collections' }).click();
  await expect(page.getByText('Desktop QA collection', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Open Desktop QA collection' }).click();
  await page.getByRole('dialog', { name: 'Desktop QA collection' }).getByRole('button', { name: 'Archive', exact: true }).click();
  await page.getByRole('dialog', { name: 'Desktop QA collection' }).getByRole('button', { name: 'Close collection details' }).click();
  await expect(page.getByRole('button', { name: 'Open Desktop QA collection' })).toHaveCount(0);
  await page.getByRole('button', { name: 'Show archived' }).click();
  await page.getByRole('button', { name: 'Open Desktop QA collection' }).click();
  await page.getByRole('dialog', { name: 'Desktop QA collection' }).getByRole('button', { name: 'Restore', exact: true }).click();
  await page.getByRole('dialog', { name: 'Desktop QA collection' }).getByRole('button', { name: 'Close collection details' }).click();
  await page.getByRole('button', { name: 'Hide archived' }).click();
  await expect(page.getByRole('button', { name: 'Open Desktop QA collection' })).toBeVisible();
  await page.getByRole('button', { name: 'Open Research references' }).click();
  const researchDetail = page.getByRole('dialog', { name: 'Research references' });
  await researchDetail.getByRole('button', { name: 'Rename', exact: true }).click();
  const renameDialog = page.getByRole('dialog', { name: 'Rename collection' });
  await renameDialog.getByRole('textbox', { name: 'New collection name' }).fill('Research references · local edit');
  await renameDialog.getByRole('button', { name: 'Rename', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Open Research references · local edit' })).toBeVisible();
  await page.reload();
  await page.getByRole('tab', { name: 'Collections' }).click();
  await page.getByRole('button', { name: 'Open Research references · local edit' }).click();
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('dialog', { name: 'Research references · local edit' }).getByRole('button', { name: 'Delete', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Open Research references · local edit' })).toHaveCount(0);
  const activityRail = page.locator('.knowledge-demo-rail-card');
  await expect(activityRail.nth(0).locator('.demo-metric').filter({ hasText: 'demo activities' }).locator('strong')).toHaveText('1');
  await expect(activityRail.nth(2)).toContainText('Created collection · Desktop QA collection · Saved locally · demo');
  await activityRail.nth(1).getByRole('button', { name: 'Reset this area' }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Knowledge examples were restored' })).toBeVisible();
  await expect(page.getByText('Desktop QA collection', { exact: true })).toHaveCount(0);
  await expect(page.getByText('Product documentation', { exact: true })).toBeVisible();
  await expect(activityRail.nth(0).locator('.demo-metric').filter({ hasText: 'demo activities' }).locator('strong')).toHaveText('0');
  await expect(activityRail.nth(2)).toContainText('No Knowledge activity has been recorded');
  expect(apiRequests).toEqual([]);
});
